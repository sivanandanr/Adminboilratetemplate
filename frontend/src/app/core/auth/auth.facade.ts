import { DirtyFormsService } from '../feedback/dirty-forms.service';
import { Injectable, computed, inject, signal } from '@angular/core';
import { Router } from '@angular/router';
import { firstValueFrom } from 'rxjs';
import { AUTH_CLOCK, AUTH_PROVIDER, AuthSession, LoginRequest, Permission, ProfilePatch, safeReturnUrl } from './auth.models';
import { SessionChannel } from './session-channel';
import { AUTH_CONFIG, apiPath } from './auth.config';

export type AuthStatus = 'checking' | 'authenticated' | 'anonymous' | 'unavailable';
export type SessionReason = 'expired' | 'logout' | 'offline';
@Injectable({ providedIn: 'root' })
export class AuthFacade {
  private readonly dirtyForms = inject(DirtyFormsService);
  private readonly provider = inject(AUTH_PROVIDER);
  private readonly router = inject(Router);
  private readonly clock = inject(AUTH_CLOCK);
  private readonly channel = inject(SessionChannel);
  private readonly config = inject(AUTH_CONFIG);
  private readonly current = signal<AuthSession | null>(null);
  private readonly currentStatus = signal<AuthStatus>('checking');
  private readonly refreshing = signal(false);
  private initialization?: Promise<void>;
  private refreshRequest?: Promise<boolean>;
  private logoutRequest?: Promise<void>;
  private generation = 0;
  private clockOffset = 0;
  readonly session = this.current.asReadonly();
  readonly status = this.currentStatus.asReadonly();
  readonly user = computed(() => this.current()?.user ?? null);
  readonly initials = computed(() => (this.user()?.displayName ?? '').split(' ').filter(Boolean).slice(0, 2).map((part) => part[0]).join('').toUpperCase());
  readonly isAuthenticated = computed(() => this.currentStatus() === 'authenticated' && !!this.current());
  readonly permissionsLoading = computed(() => this.currentStatus() === 'checking' || this.refreshing());
  readonly effectivePermissions = computed(() => new Set(this.user()?.permissions ?? []));
  readonly logoutFailed = signal(false);
  readonly expiredNotice = signal(false);
  readonly confirmLogout = signal(false);
  readonly signingOut = signal(false);

  can(permission: Permission): boolean { return this.isAuthenticated() && !this.permissionsLoading() && this.effectivePermissions().has(permission); }
  canAll(required: readonly Permission[]): boolean { return this.isAuthenticated() && !this.permissionsLoading() && required.every((permission) => this.effectivePermissions().has(permission)); }
  serverNow(): number { return this.clock() + this.clockOffset; }

  initialize(): Promise<void> {
    this.initialization ??= this.restore();
    return this.initialization;
  }
  private async restore(): Promise<void> {
    const started = this.clock();
    const generation = this.generation;
    try {
      const session = await firstValueFrom(this.provider.session());
      if (generation !== this.generation) return;
      if (session) this.accept(session, started); else this.currentStatus.set('anonymous');
    } catch { if (generation === this.generation) this.currentStatus.set('unavailable'); }
  }
  async ready(): Promise<void> { await this.initialize(); await this.refreshRequest; }
  async reconnect(): Promise<void> {
    this.currentStatus.set('checking'); this.initialization = this.restore(); await this.initialization;
    if (this.isAuthenticated() && this.router.url.startsWith('/login')) await this.router.navigateByUrl(safeReturnUrl(this.router.parseUrl(this.router.url).queryParams['returnUrl'] as string | undefined));
  }

  async signIn(request: LoginRequest): Promise<void> {
    if (!this.config.providers.includes(request.provider)) throw new Error('Authentication provider is not enabled');
    const started = this.clock();
    const generation = ++this.generation;
    const result = await firstValueFrom(this.provider.login({ ...request, returnUrl: safeReturnUrl(request.returnUrl) }));
    if (generation !== this.generation) return;
    if (result.kind === 'redirect') {
      // Redirects are generated by our BFF adapter; never follow arbitrary response URLs.
      if (!result.url.startsWith(apiPath(this.config, this.config.endpoints.challenge) + '/') || result.url.includes('\\')) throw new Error('Unsafe authentication redirect');
      window.location.assign(result.url); return;
    }
    this.accept(result.session, started); this.expiredNotice.set(false); this.logoutFailed.set(false);
    if (!this.isAuthenticated()) return;
    this.channel.send({ type: 'renewed', at: this.clock() });
    await this.router.navigateByUrl(safeReturnUrl(request.returnUrl));
  }
  revalidate(): Promise<boolean> {
    this.refreshRequest ??= this.refresh().finally(() => { this.refreshRequest = undefined; });
    return this.refreshRequest;
  }
  private async refresh(): Promise<boolean> {
    const started = this.clock();
    const generation = this.generation;
    this.refreshing.set(true);
    try {
      const session = await firstValueFrom(this.provider.session());
      if (generation !== this.generation) return false;
      if (!session) { this.invalidate('expired'); return false; }
      this.accept(session, started); return this.isAuthenticated();
    } catch { if (generation === this.generation) this.invalidate('offline', false); return false; }
    finally { this.refreshing.set(false); }
  }
  async renew(): Promise<boolean> {
    const started = this.clock();
    const generation = this.generation;
    const session = await firstValueFrom(this.provider.renew());
    if (generation !== this.generation || !this.isAuthenticated()) return false;
    this.accept(session, started); return this.isAuthenticated();
  }
  async saveProfile(patch: ProfilePatch): Promise<void> {
    const started = this.clock();
    if (!this.can('profile.edit')) throw new Error('Profile editing is not permitted');
    const generation = this.generation;
    const allowed = this.user()?.editableFields ?? [];
    const filtered = Object.fromEntries(Object.entries(patch).filter(([field]) => allowed.includes(field as keyof ProfilePatch))) as ProfilePatch;
    const session = await firstValueFrom(this.provider.updateProfile(filtered));
    if (generation === this.generation && this.isAuthenticated()) this.accept(session, started);
  }
  logout(reason: SessionReason = 'logout'): Promise<void> {
    // Security expiry must never wait behind a voluntary discard confirmation.
    if (reason !== 'logout') return this.performLogout(reason);
    this.logoutRequest ??= this.performLogout(reason).finally(() => { this.logoutRequest = undefined; });
    return this.logoutRequest;
  }
  private async performLogout(reason: SessionReason): Promise<void> {
    this.confirmLogout.set(false);
    if (reason === 'logout' && !(await this.dirtyForms.requestLeave())) return;
    this.signingOut.set(true);
    this.confirmLogout.set(false);
    this.invalidate(reason);
    try { await firstValueFrom(this.provider.logout()); this.logoutFailed.set(false); }
    catch { this.logoutFailed.set(true); }
    finally { this.signingOut.set(false); }
  }
  async retryLogout(): Promise<void> {
    try { await firstValueFrom(this.provider.logout()); this.logoutFailed.set(false); } catch { this.logoutFailed.set(true); }
  }
  invalidate(reason: SessionReason, broadcast = true): void {
    this.dirtyForms.clear();
    ++this.generation;
    this.provider.clearLocalSession();
    this.current.set(null); this.currentStatus.set('anonymous'); this.refreshing.set(false);
    this.expiredNotice.set(reason === 'expired'); this.confirmLogout.set(false);
    if (broadcast) this.channel.send({ type: 'logout', at: this.clock() });
    const returnUrl = safeReturnUrl(this.router.url);
    void this.router.navigate(['/login'], { queryParams: { reason, ...(reason === 'logout' ? {} : { returnUrl }) }, replaceUrl: true });
  }
  private accept(session: AuthSession, requestStarted: number): void {
    // Count the entire request duration conservatively; response latency cannot add session life.
    this.clockOffset = session.serverTime - requestStarted;
    if (session.expiresAt <= this.serverNow()) { this.invalidate('expired'); return; }
    this.current.set(session); this.currentStatus.set('authenticated');
  }
}
